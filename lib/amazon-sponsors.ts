/*  The single source of truth for every Amazon product on the site:    */
/*  the sponsored rows in the browse grid, the Amazon section in        */
/*  search, and the /amazon "view all" page. Empty this array and all   */
/*  three render nothing, so the app stays clean with no sponsors.      */
/*                                                                      */
/*  For each product provide:                                           */
/*    title       — product name shown on the card                      */
/*    url         — the real affiliate link (SiteStripe, tag=verzatv-20)*/
/*    asin        — Amazon product id. Powers the add-to-cart handoff.  */
/*                  Omit ONLY for search links (a search link has no    */
/*                  single product to put in a cart).                   */
/*    imageId     — id of the product photo on Amazon's image CDN. Grab */
/*                  it from the product page: the main image URL looks  */
/*                  like m.media-amazon.com/images/I/<imageId>._SL..jpg */
/*    badge       — small category tag shown on the tile                */
/*    icon        — glyph for the placeholder if the photo fails        */
/*    accent      — [from, to] gradient for the placeholder             */
/*    description — blurb shown in the in-app product modal             */
/*                                                                      */
/*  NOTE ON PRICES: we deliberately do NOT store prices. Amazon's       */
/*  Associates agreement only permits displaying prices pulled from the */
/*  Product Advertising API and refreshed at least every 24 hours, so a */
/*  hardcoded price is both wrong within a week and a terms violation.  */
/*  Shoppers see the live price on Amazon at handoff.                   */
/* ------------------------------------------------------------------ */

