export type AmazonProduct = {
  id: string;
  title: string;
  url: string;
  asin?: string;
  /** Amazon's id for the primary product photo, e.g. "61IQUadfGEL". */
  imageId?: string;
  /**
   * A background-removed copy of the photo exists locally, at
   * /amazon/<id>-<width>.webp. Generated by scripts/amazon-cutouts.py from
   * imageId. Set this and the product floats on the black card instead of
   * dragging Amazon's white studio backdrop along with it.
   */
  cutout?: boolean;
  /** Explicit image override. Wins over everything else. */
  image?: string;
  icon?: AmazonIcon;
  accent?: [string, string];
  badge?: string;
  description?: string;
};

/** Verza TV's Amazon Associates tracking tag. Every outbound link carries it. */
export const AMAZON_TAG = "verzatv-20";

