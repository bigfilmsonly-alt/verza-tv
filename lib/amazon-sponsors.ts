/**
 * A product photo straight off Amazon's image CDN, at whatever size we ask for.
 *
 * Deliberately NOT the Associates "AsinImage" widget on ws-na.amazon-adsystem.com:
 * that host is an ad-network domain, so every ad blocker drops it and a large
 * share of shoppers would see empty product cards. m.media-amazon.com is the
 * plain CDN — no blocker touches it, and it is faster.
 */
export function amazonImage(imageId: string, size = 800): string {
  return `https://m.media-amazon.com/images/I/${imageId}._SL${size}_.jpg`;
}

/** Widths generated by scripts/amazon-cutouts.py. Keep the two in step. */
const CUTOUT_WIDTHS = [400, 800, 1200];

/** The local cutout at the smallest width that still covers `size`. */
function cutoutImage(p: AmazonProduct, size: number): string {
  const w = CUTOUT_WIDTHS.find((c) => c >= size) ?? CUTOUT_WIDTHS[CUTOUT_WIDTHS.length - 1];
  return `/amazon/${p.id}-${w}.webp`;
}

/** The photo to show for a product, or undefined to fall back to the placeholder. */
export function productImage(p: AmazonProduct, size = 800): string | undefined {
  if (p.image) return p.image;
  if (p.cutout) return cutoutImage(p, size);
  return p.imageId ? amazonImage(p.imageId, size) : undefined;
}

/**
 * Widths we offer the browser. Amazon's CDN resizes on the fly from one master
 * image, so every extra width here is free to us — no assets to store, and the
 * browser downloads exactly one of them.
 *
 * Capped at 1200 on purpose: ask for more than the master and Amazon returns
 * the master rather than upscaling, which would make the `w` descriptor a lie
 * and could have the browser pick a file smaller than it bargained for.
 */
const IMAGE_WIDTHS = [300, 500, 800, 1200];

/**
 * A srcset so each screen gets a crisp image at its own pixel density: a phone
 * at 3x DPI pulls a genuinely high resolution file, while a low-DPI laptop is
 * not made to download it. A single fixed-size src cannot do both — at 500px it
 * looked soft in the product modal, which renders ~420px wide and therefore
 * wants ~1200px of real pixels on a modern phone.
 */
export function productSrcSet(p: AmazonProduct): string | undefined {
  // An explicit override is a single fixed asset — nothing to resize.
  if (p.image) return undefined;
  if (p.cutout) {
    return CUTOUT_WIDTHS.map((w) => `/amazon/${p.id}-${w}.webp ${w}w`).join(", ");
  }
  if (!p.imageId) return undefined;
  const id = p.imageId;
  return IMAGE_WIDTHS.map((w) => `${amazonImage(id, w)} ${w}w`).join(", ");
}

/**
 * Builds an Amazon cart URL that drops EVERY item in one shot, with the Verza
 * affiliate tag attached, and lands the shopper on their Amazon cart ready to
 * check out.
 *
 * This is what makes the in-app bag work: shoppers collect items inside Verza
 * TV, and a single handoff moves the whole bag over. Amazon gives affiliates no
 * checkout API and forbids framing its pages, so payment always completes on
 * amazon.com — this is as close to buying in-app as the program allows.
 *
 * Must stay a GET link (anchor / window.open). A form POST would be blocked by
 * our CSP, which pins form-action to 'self' and Stripe.
 */
export function amazonCartUrl(items: { asin: string; quantity: number }[]): string {
  const params = new URLSearchParams({ AssociateTag: AMAZON_TAG });
  items.forEach((item, i) => {
    params.set(`ASIN.${i + 1}`, item.asin);
    params.set(`Quantity.${i + 1}`, String(item.quantity));
  });
  return `https://www.amazon.com/gp/aws/cart/add.html?${params.toString()}`;
}

/** A product can only be carted if we know which single product it is. */
export function isCartable(p: AmazonProduct): boolean {
  return Boolean(p.asin);
}

/**
 * Matches an Amazon product against a search query. Every product carries the
 * shared "amazon / prime / shop / sponsored" keywords, so searching "amazon"
 * returns ALL products; product-specific words (e.g. "mascara") narrow it.
 * Token-based AND matching, case-insensitive, min 2 chars — same rules as the
 * movie search.
 */
export function amazonProductMatchesQuery(p: AmazonProduct, rawQuery: string): boolean {
  const q = rawQuery.trim().toLowerCase();
  if (q.length < 2) return false;
  const haystack = [
    p.title,
    p.badge ?? "",
    p.description ?? "",
    "amazon",
    "amzn",
    "prime",
    "amazon prime",
    "shop",
    "sponsored",
    "ad",
    "ads",
    "product",
    "products",
    "deal",
    "deals",
    "trending",
  ]
    .join(" ")
    .toLowerCase();
  return q
    .split(/\s+/)
    .filter(Boolean)
    .every((token) => haystack.includes(token));
}

